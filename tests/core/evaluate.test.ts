/**
 * Тесты сравнения попытки с секретом.
 *
 * Проверяют контракт `evaluateGuess`: количество bulls (цифра на своём месте)
 * и cows (цифра есть в секрете, но стоит не на своём месте), независимость
 * от регистра для hex и корректную работу с ведущими нулями.
 */

import { evaluateGuess } from '../../src/core/evaluate.js';

const cases: [string, string, number, number][] = [
  ['1234', '1234', 4, 0],
  ['1234', '5678', 0, 0],
  ['1234', '4321', 0, 4],
  ['1234', '1243', 2, 2],
  ['1234', '1324', 2, 2],
  ['1234', '2341', 0, 4],
  ['1234', '3456', 0, 2],
  ['1234', '1235', 3, 0],
  ['1234', '1256', 2, 0],
  ['1234', '1567', 1, 0],
  ['123456', '654321', 0, 6],
  ['0123', '3210', 0, 4],
  ['0123', '0123', 4, 0],
  ['012345', '543210', 0, 6],
  ['abcd', 'ABCD', 4, 0],
  ['aBcD', 'AbCd', 4, 0],
  ['a1b2', 'A1B3', 3, 0],
  ['12', '21', 0, 2],
  ['12', '12', 2, 0],
  ['12', '13', 1, 0],
];

describe('evaluateGuess', () => {
  it.each(cases)('secret %s, guess %s → %s bulls, %s cows', (secret, guess, bulls, cows) => {
    expect(evaluateGuess(secret, guess)).toEqual({ bulls, cows });
  });
});
